import React, { useState } from 'react';

export default function TotpQrBindStep({ onSuccess }: { onSuccess: () => void }) {
  const [isManualMode, setIsManualMode] = useState(false);
  const [otp, setOtp] = useState(['', '', '', '', '', '']);

  const handleChange = (index: number, val: string) => {
    const newOtp = [...otp];
    newOtp[index] = val.slice(-1);
    setOtp(newOtp);
    
    if (newOtp.join('').length === 6) {
      onSuccess(); 
    }
  };

  return (
    <div className="stack" style={{ maxWidth: '400px', margin: '0 auto' }}>
      {!isManualMode ? (
        <div className="stack" style={{ alignItems: 'center', textAlign: 'center' }}>
          <div>
            <div style={{ fontWeight: 600, fontSize: '14px' }}>Step 1: Scan this QR code</div>
            <div style={{ fontSize: '13px', color: 'var(--fg-muted)' }}>Scan the following QR code with your authenticator app.</div>
          </div>
          
          <div style={{ width: '120px', height: '120px', background: 'var(--border)', margin: 'var(--space-2) 0', display: 'flex', alignItems: 'center', justifyContent: 'center' }}>
             [ QR Image ]
          </div>
          
          <button className="btn" style={{ border: 'none', background: 'transparent', color: 'var(--accent)', fontSize: '13px', padding: 0, minHeight: 'auto' }} onClick={() => setIsManualMode(true)}>
            Can't scan the QR code?
          </button>
        </div>
      ) : (
        <div className="stack" style={{ textAlign: 'center' }}>
          <div>
            <div style={{ fontWeight: 600, fontSize: '14px' }}>Step 1: Copy and paste the key</div>
            <div style={{ fontSize: '13px', color: 'var(--fg-muted)' }}>Copy and paste the following key into your authenticator app.</div>
          </div>
          
          <div className="row" style={{ background: 'var(--bg)', padding: 'var(--space-2)', borderRadius: 'var(--radius)', marginTop: 'var(--space-2)', justifyContent: 'center' }}>
             <code style={{ fontSize: '12px' }}>HXJEDO4OMCJC5ALOVIOVLAODDC3I2DJSLKLDNCCCCSD</code>
          </div>
          <button className="btn" style={{ marginTop: 'var(--space-2)' }}>Copy</button>

          <button className="btn" style={{ border: 'none', background: 'transparent', color: 'var(--accent)', fontSize: '13px', padding: 0, minHeight: 'auto', marginTop: 'var(--space-4)' }} onClick={() => setIsManualMode(false)}>
            Want to scan QR code?
          </button>
        </div>
      )}

      <div style={{ borderTop: '1px solid var(--border)', margin: 'var(--space-4) 0' }}></div>

      <div className="stack" style={{ alignItems: 'center' }}>
        <div style={{ textAlign: 'center', marginBottom: 'var(--space-2)' }}>
          <div style={{ fontWeight: 600, fontSize: '14px' }}>Step 2: Enter the one-time code</div>
          <div style={{ fontSize: '13px', color: 'var(--fg-muted)' }}>Enter the 6-digit verification code generated by the authenticator app.</div>
        </div>
        
        <div className="row" style={{ gap: 'var(--space-2)', justifyContent: 'center' }}>
          {otp.map((digit, i) => (
            <input 
              key={i}
              type="text" 
              className="input" 
              style={{ width: '45px', textAlign: 'center', fontSize: '18px', fontWeight: 'bold' }}
              value={digit}
              onChange={(e) => handleChange(i, e.target.value)}
            />
          ))}
        </div>
      </div>
    </div>
  );
}